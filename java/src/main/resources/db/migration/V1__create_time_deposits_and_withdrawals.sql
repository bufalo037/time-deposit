-- Initial schema for the README "Database Setup": tables timeDeposits and withdrawals.
-- Naming: snake_case (time_deposits, plan_type, time_deposit_id), because PostgreSQL folds unquoted identifiers to
-- lower case. JPA entities and the API keep the README's camelCase names (ADR 0004).
-- Money: numeric(19,2), exact decimal at cent precision (ADR 0004).

CREATE TABLE time_deposits (
    id        integer       GENERATED BY DEFAULT AS IDENTITY,
    -- No CHECK on the values: new plan types must not need a schema change (README extensibility), and the
    -- calculator already gives unknown plan types no interest.
    plan_type varchar(20)   NOT NULL,
    days      integer       NOT NULL,
    balance   numeric(19,2) NOT NULL,
    CONSTRAINT pk_time_deposits PRIMARY KEY (id)
);

CREATE TABLE withdrawals (
    id              integer       GENERATED BY DEFAULT AS IDENTITY,
    time_deposit_id integer       NOT NULL,
    amount          numeric(19,2) NOT NULL,
    -- README column name. "date" is a non-reserved keyword in PostgreSQL, so it's valid unquoted.
    date            date          NOT NULL,
    CONSTRAINT pk_withdrawals PRIMARY KEY (id),
    CONSTRAINT fk_withdrawals_time_deposits FOREIGN KEY (time_deposit_id) REFERENCES time_deposits (id)
);

-- PostgreSQL doesn't index foreign keys automatically. Withdrawals are looked up per time deposit.
CREATE INDEX idx_withdrawals_time_deposit_id ON withdrawals (time_deposit_id);
